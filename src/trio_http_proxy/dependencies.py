"""Small structural contracts for the proxy cache's external effects."""

from collections.abc import Callable, Sequence
from typing import Any, Protocol


class CacheBackend(Protocol):
    """Operations owned by one ProxyCache; async methods run on its bridge loop.

    ``setup`` is synchronous. The cache owns setup and close, including when the
    backend is supplied by a caller. Do not share a backend between live caches.
    Cashews Cache implements this contract without an adapter.
    """

    def setup(self, settings_url: str, *, suppress: bool) -> object: ...
    async def ping(self) -> bytes: ...
    async def get(self, key: str, default: Any = None) -> Any: ...
    async def set(
        self, key: str, value: Any, *, expire: float | None = None
    ) -> object: ...
    async def incr(
        self, key: str, value: int = 1, expire: float | None = None
    ) -> int: ...
    async def get_expire(self, key: str) -> int: ...
    async def expire(self, key: str, timeout: float) -> object: ...
    async def delete_match(self, pattern: str) -> None: ...
    async def clear(self) -> None: ...
    async def close(self) -> None: ...


class HostResolver(Protocol):
    """Blocking DNS lookup, run in the bridge's executor, never on Trio's thread."""

    def __call__(self, host: str, /) -> Sequence[str]: ...


class ThreadHandle(Protocol):
    def start(self) -> None: ...
    def is_alive(self) -> bool: ...
    def join(self, timeout: float | None = None) -> None: ...


class ThreadFactory(Protocol):
    def __call__(
        self, *, target: Callable[[], None], daemon: bool, name: str
    ) -> ThreadHandle: ...
